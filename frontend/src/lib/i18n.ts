export type MessageKey = keyof typeof greekMessages;
export type MessageParams = Record<string, string | number>;
export type Translator = (key: MessageKey, params?: MessageParams) => string;

export function createTranslator(locale: Locale): Translator {
  return (key, params = {}) => {
    const template = locale === "el" ? greekMessages[key] : key;
    return template.replace(/\{(\w+)\}/g, (_, name: string) => {
      if (!(name in params)) throw new Error(`Missing translation parameter: ${name}`);
      return String(params[name]);
    });
  };
}

// Only known system/validation messages are translated; unknown diagnostics remain visible.
export function localizeMessage(locale: Locale, message: string): string {
  return Object.hasOwn(greekMessages, message) && !/\{\w+\}/.test(message)
    ? createTranslator(locale)(message as MessageKey)
    : message;
}

export function intlLocale(locale: Locale): string {
  return locale === "el" ? "el-GR" : "en-GB";
}

export function formatTuition(
  locale: Locale,
  school: { isPrivate: boolean; tuitionFrom: number | null; tuitionTo: number | null },
  detail = false,
): string {
  const t = createTranslator(locale);
  if (!school.isPrivate) return t("Public school");
  if (school.tuitionFrom == null) return t(detail ? "Contact school for tuition" : "Tuition not listed");
  const currency = new Intl.NumberFormat(intlLocale(locale), { style: "currency", currency: "EUR", minimumFractionDigits: 0, maximumFractionDigits: 2 });
  const amount = `${currency.format(school.tuitionFrom)}${school.tuitionTo == null ? "+" : ` – ${currency.format(school.tuitionTo)}`}`;
  return t(detail ? "{amount} per year" : "{amount} / year", { amount });
}
